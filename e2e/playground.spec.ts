import { test, expect } from '@playwright/test'
test('examples, rounding, compact form and validation', async ({ page }) => {
 await page.goto('/')
 await expect(page.getByText("curl 'https://slovima.dlbr.cloud/api/v1/convert?amount=10.800%2C50&script=latn'")).toBeVisible()
 await expect(page.getByText('Odgovor sadrži oba zapisa:', { exact: false })).toBeVisible()
 await expect(page.getByText('za ćirilicu.', { exact: false })).toBeVisible()
 await expect(page.locator('.api-example pre').nth(1)).toContainText('desethiljadaosamstodinaraipedesetpara')
 const field = page.getByLabel('Iznos u dinarima')
 await expect(page.locator('.result')).toHaveText('deset hiljada osamsto dinara i pedeset para')
 await page.getByRole('button', { name: '99,995' }).click()
 await expect(field).toHaveValue('99,995')
 await expect(page.locator('.api-example pre').first()).toContainText('amount=99%2C995')
 await expect(page.locator('.api-example pre').nth(1)).toContainText('sto dinara')
 await expect(page.locator('.result')).toHaveText('sto dinara')
 await page.getByLabel('Ћирилица').check()
 await expect(page.locator('.result')).toHaveText('сто динара')
 await expect(page.locator('.api-example pre').first()).toContainText('&script=cyrl')
 await expect(page.locator('.api-example pre').nth(1)).toContainText('сто динара')
 await page.getByLabel('Latinica').check()
 await page.getByLabel('Bez razmaka').check()
 await expect(page.locator('.result')).toHaveText('stodinara')
 await field.fill('10000.20')
 await expect(page.locator('.result')).toHaveText('desethiljadadinaraidvadesetpara')
 await field.fill('0.005'); await field.blur()
 await expect(page.getByRole('alert')).toContainText('Dvosmislen')
 await expect(page.getByText('PRIMER ODGOVORA')).toBeVisible()
 await field.fill("1'2")
 await expect(page.locator('.api-example pre').first()).toContainText('amount=1%272')
 await field.fill('12,abc'); await field.blur()
 await expect(page.getByRole('alert')).toBeVisible()
 await expect(page.getByRole('button', { name: 'Kopiraj zapis' })).toBeDisabled()
 await field.fill('0,01')
 await expect(page.getByRole('alert')).toHaveCount(0)
 await expect(page.locator('.result')).toHaveText('jednapara')
})
test('copies the selected output', async ({ page, context }) => {
 await context.grantPermissions(['clipboard-read', 'clipboard-write'])
 await page.goto('/')
 await page.getByRole('button', { name: 'Kopiraj zapis' }).click()
 await expect(page.getByText('Kopirano u clipboard.')).toBeVisible()
 expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('deset hiljada osamsto dinara i pedeset para')
 await page.getByRole('button', { name: 'Kopiraj curl' }).click()
 await expect(page.getByText('Komanda je kopirana.')).toBeVisible()
 expect(await page.evaluate(() => navigator.clipboard.readText())).toBe("curl 'https://slovima.dlbr.cloud/api/v1/convert?amount=10.800%2C50&script=latn'")
})
