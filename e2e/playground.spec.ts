import { test, expect } from '@playwright/test'
test('examples, rounding, compact form and validation', async ({ page }) => {
 await page.goto('/')
 await expect(page.getByText("curl 'https://slovima.dlbr.cloud/api/v1/convert?amount=10000.20'")).toBeVisible()
 const field = page.getByLabel('Iznos u dinarima')
 await expect(page.locator('.result')).toHaveText('deset hiljada osamsto dinara i pedeset para')
 await page.getByRole('button', { name: '99,995' }).click()
 await expect(field).toHaveValue('99,995')
 await expect(page.locator('.result')).toHaveText('sto dinara')
 await page.getByLabel('Bez razmaka').check()
 await expect(page.locator('.result')).toHaveText('stodinara')
 await field.fill('10000.20')
 await expect(page.locator('.result')).toHaveText('desethiljadadinaraidvadesetpara')
 await field.fill('12,abc'); await field.blur()
 await expect(page.getByRole('alert')).toBeVisible()
 await expect(page.getByRole('button', { name: 'Kopiraj zapis' })).toBeDisabled()
 await field.fill('0,01')
 await expect(page.getByRole('alert')).toHaveCount(0)
 await expect(page.locator('.result')).toHaveText('jednapara')
})
test('copies the selected output', async ({ page, context }) => {
 await context.grantPermissions(['clipboard-read', 'clipboard-write'])
 await page.goto('/')
 await page.getByRole('button', { name: 'Kopiraj zapis' }).click()
 await expect(page.getByText('Kopirano u clipboard.')).toBeVisible()
 expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('deset hiljada osamsto dinara i pedeset para')
})
